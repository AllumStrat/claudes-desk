// Copies Jacob's skills into skill/ and regenerates src/core/rules.generated.js,
// so the Worker (which has no file system) carries the same rules text.
//
//   node scripts/sync-skill.js /path/to/skills
//
// The path is the folder that holds seo-writing/, anti-ai-writing/ and
// copywriting/. With no path it only regenerates from the copies in skill/.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const dest = path.join(root, 'skill');

// File in skill/ -> export name in rules.generated.js (null: copied, not exported)
export const FILES = {
  'seo-writing/SKILL.md': 'SEO_WRITING_SKILL',
  'seo-writing/PARAMETERS.md': 'SEO_WRITING_PARAMETERS',
  'seo-writing/scripts/check.py': null,
  'anti-ai-writing/SKILL.md': 'ANTI_AI_WRITING_SKILL',
  'copywriting/SKILL.md': 'COPYWRITING_SKILL',
};

export function renderModule(read) {
  const lines = [
    '// Generated by scripts/sync-skill.js from the files in skill/. Do not edit;',
    '// change the skill and run `npm run sync-skill` instead.',
    '',
  ];
  for (const [file, name] of Object.entries(FILES)) {
    if (name) lines.push(`export const ${name} = ${JSON.stringify(read(file))};`, '');
  }
  return lines.join('\n');
}

function main() {
  const src = process.argv[2];
  if (src) {
    for (const file of Object.keys(FILES)) {
      const from = path.join(src, file);
      if (!fs.existsSync(from)) throw new Error(`missing ${from}`);
      fs.mkdirSync(path.dirname(path.join(dest, file)), { recursive: true });
      fs.copyFileSync(from, path.join(dest, file));
    }
  }
  const out = renderModule((f) => fs.readFileSync(path.join(dest, f), 'utf8'));
  fs.writeFileSync(path.join(root, 'src/core/rules.generated.js'), out);
  console.log(src ? `Copied skills from ${src} and regenerated the rules module.` : 'Regenerated the rules module.');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
